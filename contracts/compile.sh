#!/bin/bash
# Compiles contracts/PoWFaucetBatcher.sol into src/eth/claimtx/BatcherArtifact.ts with a pinned
# solc in docker (the same way ethpandaops/spamoor builds its contracts).
#
# The faucet deploys the batcher through the deterministic deployment proxy, so the bytecode is the
# address: the fixed compiler version and settings below mean every faucet build derives the same
# batcher address on every chain. The artifact is committed; run this only when the contract
# changes, and expect the address to change with it. Needs docker and jq.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOLC_VERSION="0.8.30"

# no metadata hash / CBOR trailer in the bytecode: the address must not move with a comment
SOLC_ARGS="--optimize --optimize-runs 1000 --evm-version cancun --metadata-hash none --no-cbor-metadata"

# compile_contract <source dir (mounted as /contracts)> <contract name> <artifact path> <const prefix>
compile_contract() {
  local srcdir="$1" contract="$2" artifact="$3" prefix="$4"
  local contract_json contract_key contract_abi contract_bin contract_runtime
  contract_json=$(docker run --rm -v "$srcdir":/contracts "ethereum/solc:$SOLC_VERSION" "/contracts/$contract.sol" --combined-json abi,bin,bin-runtime $SOLC_ARGS)

  # the key is "/contracts/X.sol:X" or "contracts/X.sol:X" depending on the solc build
  contract_key=$(echo "$contract_json" | jq -r '.contracts | keys[]' | grep -E "^/?contracts/$contract.sol:$contract\$" | head -1)
  contract_abi=$(echo "$contract_json" | jq -c --arg k "$contract_key" '.contracts[$k].abi')
  contract_bin=$(echo "$contract_json" | jq -r --arg k "$contract_key" '.contracts[$k].bin')
  contract_runtime=$(echo "$contract_json" | jq -r --arg k "$contract_key" '.contracts[$k]["bin-runtime"]')
  if [ -z "$contract_key" ] || [ "$contract_abi" == "null" ] || [ -z "$contract_bin" ] || [ "$contract_bin" == "null" ] || [ -z "$contract_runtime" ] || [ "$contract_runtime" == "null" ]; then
    echo "could not find $contract in the compiler output" >&2
    echo "$contract_json" | jq -r '.contracts | keys[]' >&2
    exit 1
  fi

  cat > "$artifact" <<EOF2
// Generated by contracts/compile.sh from $(realpath --relative-to="$SCRIPT_DIR/.." "$srcdir")/$contract.sol. Do not edit.
// solc $SOLC_VERSION, $SOLC_ARGS

/** creation bytecode of $contract (no constructor arguments) */
export const ${prefix}_BYTECODE = "0x$contract_bin";

/** runtime bytecode: what eth_getCode returns at a deployed $contract */
export const ${prefix}_RUNTIME_BYTECODE = "0x$contract_runtime";

export const ${prefix}_ABI = $contract_abi as const;

export const ${prefix}_COMPILER = "$SOLC_VERSION";
EOF2

  echo "wrote $(realpath --relative-to="$SCRIPT_DIR/.." "$artifact"): $(( ${#contract_bin} / 2 )) bytes of bytecode, solc $SOLC_VERSION"
}

compile_contract "$SCRIPT_DIR" PoWFaucetBatcher "$SCRIPT_DIR/../src/eth/claimtx/BatcherArtifact.ts" BATCHER
